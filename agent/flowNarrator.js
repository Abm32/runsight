'use strict';

const fs = require('fs');
const path = require('path');

/**
 * Build a human-readable narrative and a caption timeline from exploration data.
 *
 * @param {{steps: Array, summary: string, pages: Array}} result - from explore()
 * @param {Object} opts - run options (mode, model, coverage)
 * @returns {{
 *   captions: Array<{ tMs: number, text: string, durationMs: number }>,
 *   markdown: string,
 *   write: (outputDir: string) => string
 * }}
 */
function buildNarrative(result, opts = {}) {
  const steps = result.steps || [];
  const pages = result.pages || [];

  // Caption timeline: one caption per meaningful action, aligned to video time.
  const actionSteps = steps.filter(s => s.kind === 'action' || s.kind === 'key');
  const captions = actionSteps.map((s, i) => {
    const next = actionSteps[i + 1];
    const start = typeof s.tMs === 'number' ? s.tMs : i * 2000;
    const end = next && typeof next.tMs === 'number' ? next.tMs : start + 3000;
    return {
      tMs: Math.max(0, start),
      durationMs: Math.max(1200, end - start),
      text: s.caption || s.action || 'Exploring'
    };
  });

  // Human-readable narrative.
  const lines = [];
  lines.push('# Demo Flow');
  lines.push('');
  lines.push(`Generated by RunSight (${opts.mode || 'heuristic'} mode${opts.model ? `, ${opts.model}` : ''}, coverage: ${opts.coverage || 'happy'}).`);
  lines.push('');

  if (pages.length) {
    lines.push('## Pages visited');
    lines.push('');
    for (const p of pages) {
      lines.push(`### ${p.url}`);
      if (p.summary) lines.push(`> ${p.summary}`);
      lines.push('');
      if (p.topActions && p.topActions.length) {
        lines.push('Key actions detected:');
        for (const a of p.topActions) {
          const dest = a.predictedDestination ? ` → ${a.predictedDestination}` : '';
          lines.push(`- **${a.label}**${dest}`);
        }
        lines.push('');
      }
    }
  }

  lines.push('## Walkthrough');
  lines.push('');
  let n = 1;
  for (const s of actionSteps) {
    const dest = s.predictedDestination ? ` — leads to ${s.predictedDestination}` : '';
    const nav = s.navigated ? ` (navigated ${s.fromUrl} → ${s.toUrl})` : '';
    lines.push(`${n}. ${s.caption || s.action}${dest}${nav}`);
    n++;
  }
  lines.push('');
  lines.push('## Summary');
  lines.push('');
  lines.push(result.summary || 'No actions taken.');
  lines.push('');

  const markdown = lines.join('\n');

  return {
    captions,
    markdown,
    write(outputDir) {
      const p = path.join(outputDir, 'flow.md');
      fs.writeFileSync(p, markdown);
      return p;
    }
  };
}

module.exports = { buildNarrative };
